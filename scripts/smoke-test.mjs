import assert from "node:assert/strict";

const baseUrl = process.env.BASE_URL ?? "http://localhost:3000";
const login = await fetch(`${baseUrl}/api/auth/login`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email: "admin@cidadefacil.local", password: "CidadeFacil@2026" }) });
if (login.status !== 200) throw new Error(`Login falhou: ${await login.text()}`);
const cookie = login.headers.getSetCookie()[0].split(";")[0];
const headers = { "Content-Type": "application/json", Cookie: cookie };
const dashboard = await fetch(`${baseUrl}/dashboard`, { headers });
assert.equal(dashboard.status, 200, "Dashboard protegido não carregou.");
for (const path of ["/secretarias", "/equipes", "/usuarios", "/mapa", "/relatorios"]) {
  const page = await fetch(`${baseUrl}${path}`, { headers });
  assert.equal(page.status, 200, `A página ${path} não carregou.`);
}
const departmentsList = await fetch(`${baseUrl}/api/departments`, { headers }).then((response) => response.json());
assert.equal(departmentsList.items.length, 20, "A lista de secretarias de Seropédica está incompleta.");
const settingsResponse = await fetch(`${baseUrl}/api/admin/settings`, { headers });
assert.equal(settingsResponse.status, 200, "Consulta das configurações falhou.");
const settings = await settingsResponse.json();
assert.equal(settings.municipality.governmentName, "Prefeitura Municipal de Seropédica");
assert.equal(settings.priorities.length, 4, "Prazos das prioridades estão incompletos.");
const preferencesResponse = await fetch(`${baseUrl}/api/admin/settings`, { method: "PATCH", headers, body: JSON.stringify({ section: "notifications", urgentRequests: true, deadlineAlerts: true, dailyDigest: false, teamConclusions: true }) });
assert.equal(preferencesResponse.status, 200, "Persistência das preferências de notificação falhou.");
const suffix = Date.now();
const categoryResponse = await fetch(`${baseUrl}/api/admin/categories`, { method: "POST", headers, body: JSON.stringify({ name: `Categoria Teste ${suffix}`, color: "#0891b2" }) });
assert.equal(categoryResponse.status, 201, "Criação de categoria falhou.");
const category = await categoryResponse.json();
const categoryUpdate = await fetch(`${baseUrl}/api/admin/categories/${category.id}`, { method: "PATCH", headers, body: JSON.stringify({ name: `Categoria Atualizada ${suffix}`, color: "#0e7490" }) });
assert.equal(categoryUpdate.status, 200, "Atualização de categoria falhou.");
const categoryDelete = await fetch(`${baseUrl}/api/admin/categories/${category.id}`, { method: "DELETE", headers });
assert.equal(categoryDelete.status, 200, "Exclusão de categoria sem vínculos falhou.");
const departmentResponse = await fetch(`${baseUrl}/api/admin/departments`, { method: "POST", headers, body: JSON.stringify({ name: `Secretaria Teste ${suffix}`, managerName: "Gestor Automatizado" }) });
assert.equal(departmentResponse.status, 201, "Criação de secretaria falhou.");
const department = await departmentResponse.json();
const teamResponse = await fetch(`${baseUrl}/api/admin/teams`, { method: "POST", headers, body: JSON.stringify({ name: `Equipe Teste ${suffix}`, departmentId: department.id, status: "Disponível", memberCount: 3 }) });
assert.equal(teamResponse.status, 201, "Criação de equipe falhou.");
const team = await teamResponse.json();
const userResponse = await fetch(`${baseUrl}/api/admin/users`, { method: "POST", headers, body: JSON.stringify({ name: "Usuário Automatizado", email: `teste.${suffix}@cidadefacil.local`, password: "Teste@2026", role: "Servidor", departmentId: department.id }) });
assert.equal(userResponse.status, 201, "Criação de usuário falhou.");
const managedUser = await userResponse.json();
const userUpdate = await fetch(`${baseUrl}/api/admin/users/${managedUser.id}`, { method: "PATCH", headers, body: JSON.stringify({ name: "Usuário Automatizado", email: managedUser.email, role: "Gestor", status: "Ativo", departmentId: department.id }) });
assert.equal(userUpdate.status, 200, "Atualização de usuário falhou.");
for (const [url, label] of [[`/api/admin/users/${managedUser.id}`, "usuário"], [`/api/admin/teams/${team.id}`, "equipe"], [`/api/admin/departments/${department.id}`, "secretaria"]]) {
  const response = await fetch(`${baseUrl}${url}`, { method: "DELETE", headers });
  assert.equal(response.status, 200, `Exclusão de ${label} falhou.`);
}
const create = await fetch(`${baseUrl}/api/requests`, { method: "POST", headers, body: JSON.stringify({ title: "Teste automatizado do fluxo", description: "Solicitação criada pelo smoke test.", category: "Iluminação Pública", priority: "Urgente", address: "Rua de Teste", neighborhood: "Fazenda Caxias", postalCode: "23895-295", latitude: "-22.743889", longitude: "-43.707500" }) });
if (create.status !== 201) throw new Error(`Criação falhou: ${await create.text()}`);
const created = await create.json();
assert.match(created.protocol, /^\d{4}-\d{7}$/);
const initialNotificationsResponse = await fetch(`${baseUrl}/api/notifications`, { headers });
assert.equal(initialNotificationsResponse.status, 200, "Geração dos alertas de SLA falhou.");
const initialNotifications = await initialNotificationsResponse.json();
assert.ok(initialNotifications.items.some((item) => item.requestId === created.id && item.title.includes("Prazo")), "Alerta de prazo próximo não foi gerado.");
const upload = new FormData();
upload.append("files", new Blob([Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=", "base64")], { type: "image/png" }), "teste.png");
const uploadResponse = await fetch(`${baseUrl}/api/requests/${created.protocol}/attachments`, { method: "POST", headers: { Cookie: cookie }, body: upload });
assert.equal(uploadResponse.status, 201, "Upload de foto falhou.");
for (const body of [{ department: "Secretaria Municipal de Transporte e Serviços Públicos" }, { team: "Equipe de Iluminação 01" }, { claim: true }, { status: "Em andamento" }, { status: "Concluída", resolutionNote: "Iluminação restabelecida e ponto testado pela equipe." }]) {
  const response = await fetch(`${baseUrl}/api/requests/${created.protocol}`, { method: "PATCH", headers, body: JSON.stringify(body) });
  if (response.status !== 200) throw new Error(`Atualização falhou: ${await response.text()}`);
}
const detail = await fetch(`${baseUrl}/api/requests/${created.protocol}`, { headers });
assert.equal(detail.status, 200);
const result = await detail.json();
assert.equal(result.status, "Concluída");
assert.equal(result.department, "Secretaria Municipal de Transporte e Serviços Públicos");
assert.equal(result.team, "Equipe de Iluminação 01");
assert.equal(result.assignee?.email ?? result.assignee?.name, "Matheus Vieira");
assert.ok(result.history.length >= 5);
assert.equal(result.attachments.length, 1);
assert.ok(result.responseDueAt, "Prazo de primeira resposta não foi calculado.");
assert.ok(result.resolutionDueAt, "Prazo de resolução não foi calculado.");
assert.ok(result.firstRespondedAt, "Primeira resposta não foi registrada.");
const imageResponse = await fetch(`${baseUrl}/api/attachments/${result.attachments[0].id}`, { headers: { Cookie: cookie } });
assert.equal(imageResponse.status, 200, "Consulta do anexo falhou.");
assert.equal(imageResponse.headers.get("content-type"), "image/png");
const searchResponse = await fetch(`${baseUrl}/api/search?q=${encodeURIComponent(created.protocol)}`, { headers });
assert.equal(searchResponse.status, 200, "Busca global falhou.");
const searchResult = await searchResponse.json();
assert.ok(searchResult.items.some((item) => item.id === created.id), "Solicitação não apareceu na busca global.");
const reportResponse = await fetch(`${baseUrl}/api/reports/requests?period=all`, { headers });
assert.equal(reportResponse.status, 200, "Relatório consolidado falhou.");
const report = await reportResponse.json();
assert.ok(report.summary.total >= 1, "Relatório não contabilizou solicitações.");
const csvResponse = await fetch(`${baseUrl}/api/reports/requests?period=all&format=csv`, { headers });
assert.equal(csvResponse.status, 200, "Exportação CSV falhou.");
assert.match(csvResponse.headers.get("content-type") ?? "", /text\/csv/);
assert.match(await csvResponse.text(), new RegExp(created.protocol));
const notificationsResponse = await fetch(`${baseUrl}/api/notifications`, { headers });
assert.equal(notificationsResponse.status, 200, "Consulta de notificações falhou.");
const notificationData = await notificationsResponse.json();
assert.ok(notificationData.items.some((item) => item.requestId === created.id), "Eventos do fluxo não geraram notificações.");
const readResponse = await fetch(`${baseUrl}/api/notifications`, { method: "PATCH", headers });
assert.equal(readResponse.status, 200, "Marcação das notificações como lidas falhou.");
console.log(`Smoke test concluído com ${created.protocol}.`);
